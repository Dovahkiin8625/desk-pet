/**
 * 认「我要去做某件事」这句话。
 *
 * ## 为什么要有它
 *
 * 桌宠偶尔会只回一句话就把活儿「应」了——「好嘞，我去给你放一首」——
 * 看着像去做了，其实一个字都没交出去。用户那边一点动静都没有，
 * 还以为桌宠在忙，聊天记录里也看不出出了什么事。
 *
 * 提示词里已经反复强调「要动手就得把事交出去」，模型仍然会漏
 * （同一个模型、同一句话，实测大约每五次漏一次）。
 * 所以这里再兜一层：**说了要做，就得真的交出去。**
 *
 * ## 认得准比认得多要紧
 *
 * - 认漏了 = 「说了要去做却什么都没做」——那正是要治的毛病；
 * - 认多了 = 多一个后台任务（看板上看得见，用户自己就能停掉）。
 *
 * 所以宁可认多。
 */

/**
 * 动作动词：跟在「我去」「给你」后面的那个词。
 *
 * **只收「桌宠真的干得出来」的动作**：聊天、陪人、记东西那些不算
 * （「我帮你记下了」不是一件要交出去做的事）。
 */
const ACTION_VERBS =
  '放播唱挑挑选查找搜开关做弄整拉翻读写跑试下下载翻译整理安排准备取删移复启停切调设置问答数理汇总';

/** 承诺的几种说法。 */
const PROMISE_PATTERNS = [
  // 我去给你放 / 我去查一下
  new RegExp(`我去[^，。！？]{0,3}?[${ACTION_VERBS}]`),
  // 我来帮你查
  new RegExp(`我来[^，。！？]{0,3}?[${ACTION_VERBS}]`),
  // 我这就 / 我那就
  /我(?:这|那)就/,
  // 交给我
  /交给我/,
  // 给你放一首 / 帮你找一下
  new RegExp(`(?:给|帮)你[^，。！？]{0,3}?[${ACTION_VERBS}]`),
];

/**
 * 问句不算承诺。
 *
 * 「要不要我放首歌？」是在问，不是在做——那句话说完，用户还没点头，
 * 桌宠不该自己动起来。
 */
const QUESTION = /[？?]|要不要|好不好|行吗|可以吗|好吗/;

/**
 * 这句话是不是在承诺「我要去做某件事」。
 *
 * @param {string} text 桌宠说的话
 * @returns {boolean}
 */
export function promisesAction(text) {
  const s = String(text || '');
  if (!s) return false;
  // **一句一句看**：一句里既有问句又有承诺时，按句分开判断。
  // 逗号与句号切开，问号留着——它是「这是不是在问」的标志。
  return s
    .split(/[，,。；;]/)
    .some((clause) => {
      const c = clause.trim();
      if (!c) return false;
      if (QUESTION.test(c)) return false;
      return PROMISE_PATTERNS.some((re) => re.test(c));
    });
}
